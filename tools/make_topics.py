def parse_pairs(text):
    out = []
    for tok in text.split():
        a, b = tok.split("/")
        assert a and b and a != b, tok
        out.append((a, b))
    return out


def main(out_path):
    sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
    import topics_more as M
    ww, seen = [], set()
    merged = {c: WW.get(c, "") + "\n" + M.WW_MORE.get(c, "") for c in list(WW) + [c for c in M.WW_MORE if c not in WW]}
    for cat, text in merged.items():
        for a, b in parse_pairs(text):
            key = frozenset((a, b))
            assert key not in seen, f"duplicate pair {a}/{b}"
            seen.add(key)
            ww.append({"c": cat, "a": a, "b": b})
    ng, seen_ng = [], set()
    for cat in NG:
        for w in (NG[cat] + "\n" + M.NG_MORE.get(cat, "")).split():
            assert w not in seen_ng, f"duplicate NG word {w}"
            seen_ng.add(w)
            ng.append({"c": cat, "w": w})
    def uniq(xs, label):
        xs = [x.strip() for x in xs if x.strip()]
        d = [x for x in set(xs) if xs.count(x) > 1]
        assert not d, f"duplicate {label}: {d}"
        return xs
    spy = uniq(M.SPY_PLACES, "spy place")
    sync = uniq(M.SYNC_PROMPTS, "sync prompt")
    questions = uniq(M.QUESTIONS, "question")
    guess = sorted({w for p in ww if p["c"] in M.GUESS_CATEGORIES for w in (p["a"], p["b"])})
    os.makedirs(os.path.dirname(out_path), exist_ok=True)
    with open(out_path, "w", encoding="utf-8") as f:
        json.dump({"version": 2, "wordwolf": ww, "ng": ng, "spy": spy, "sync": sync, "guess": guess, "questions": questions},
                  f, ensure_ascii=False, separators=(",", ":"))
    print("spy places:", len(spy), " sync prompts:", len(sync), " guess words:", len(guess), " questions:", len(questions))
    by = {}
    for p in ww:
        by[p["c"]] = by.get(p["c"], 0) + 1
    print("wordwolf pairs:", len(ww), by)
    print("ng words:", len(ng), {c: sum(1 for x in ng if x["c"] == c) for c in NG})


if __name__ == "__main__":
    main(sys.argv[1] if len(sys.argv) > 1 else "app/src/main/assets/topics.json")
